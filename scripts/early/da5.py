import itertools, numpy as np
from collections import deque
phi=(1+5**.5)/2
# A5 as even permutations of 5 points, tuples
G=[p for p in itertools.permutations(range(5)) if sum(1 for i in range(5) for j in range(i) if p[i]<p[j])%2==0]
mul=lambda a,b: tuple(a[b[i]] for i in range(5))      # (a*b)(i)=a(b(i))
inv=lambda a: tuple(sorted(range(5),key=lambda i:a[i]))
e=tuple(range(5)); conj=lambda g,h: mul(mul(g,h),inv(g))
def cyc(p):
    seen=set(); t=[]
    for i in range(5):
        if i in seen: continue
        L=0;j=i
        while j not in seen: seen.add(j); j=p[j]; L+=1
        t.append(L)
    return tuple(sorted(t,reverse=True))
classes={}
for g in G:
    if any(g in c for c in classes.values()): continue
    c=frozenset(conj(h,g) for h in G); classes[g]=c
cls=list(classes.values()); print('Q1 |A5| =',len(G),'| class sizes',sorted(len(c) for c in cls))
# centralizer irreps -> anyon count and dims (centralizers: A5, V4 (order 4), C3, C5, C5)
cent={c:[h for h in G if conj(h,next(iter(c)))==next(iter(c))] for c in cls}
def n_irreps(H):  # number of conjugacy classes of subgroup H
    left=set(H); k=0
    while left:
        x=left.pop(); orb={conj(h,x) for h in H}; left-=orb; k+=1
    return k
anyons=[]; 
irrep_dims={60:[1,3,3,4,5]}
for c in cls:
    H=cent[c]; k=n_irreps(H)
    dims=irrep_dims.get(len(H),[1]*k)        # centralizers other than A5 are abelian -> 1-dim irreps
    for d in dims: anyons.append(len(c)*d)
print('   D(A5) anyon types:',len(anyons),'| quantum dimensions:',sorted(anyons),'| all integers:',all(float(a).is_integer() for a in anyons),'| sum d^2 =',sum(a*a for a in anyons))
# Q2: braid action on 3 fluxes from a 5-cycle class with product e
C5=[c for c in cls if len(c)==12 and cyc(next(iter(c)))==(5,)][0]
states=[(a,b,c) for a in C5 for b in C5 for c in C5 if mul(mul(a,b),c)==e]
idx={s:i for i,s in enumerate(states)}
def s1(s): a,b,c=s; return (conj(a,b),a,c)
def s2(s): a,b,c=s; return (a,conj(b,c),b)
P1=tuple(idx[s1(s)] for s in states); P2=tuple(idx[s2(s)] for s in states)
print('Q2 configurations (a,b,c in 5-cycle class, abc=e):',len(states),'| braids map basis->basis (permutations):',len(set(P1))==len(states) and len(set(P2))==len(states))
# group generated by P1,P2 (BFS on permutations)
comp=lambda p,q: tuple(p[q[i]] for i in range(len(q)))
idp=tuple(range(len(states))); seen={idp}; dq=deque([idp])
while dq and len(seen)<2_000_000:
    x=dq.popleft()
    for g in (P1,P2):
        y=comp(g,x)
        if y not in seen: seen.add(y); dq.append(y)
print('   braid group image order (permutations of the flux basis):',len(seen),'(finite)' if not dq else '(search capped)')
# Q3: permutation representation of A5 on the 12 five-cycles of class C5 (conjugation action) and irrep projections
Cl=sorted(C5); ci={h:i for i,h in enumerate(Cl)}
def perm_mat(g):
    M=np.zeros((12,12))
    for h in Cl: M[ci[conj(g,h)],ci[h]]=1
    return M
# characters of A5 by cycle type and 5-cycle class label
cls5=[c for c in cls if len(c)==12]; A,B=cls5[0],cls5[1]
def chi(name,g):
    t=cyc(g)
    if t==(1,1,1,1,1): return {'1':1,'3':3,"3'":3,'4':4,'5':5}[name]
    if t==(2,2,1): return {'1':1,'3':-1,"3'":-1,'4':0,'5':1}[name]
    if t==(3,1,1): return {'1':1,'3':0,"3'":0,'4':1,'5':-1}[name]
    inA=g in A
    if name=='3': return phi if inA else 1-phi
    if name=="3'": return 1-phi if inA else phi
    return {'1':1,'4':-1,'5':0}[name]
mult={}
for name,d in [('1',1),('3',3),("3'",3),('4',4),('5',5)]:
    Pm=sum(chi(name,g)*perm_mat(g) for g in G)*d/60
    mult[name]=round(np.trace(Pm)/d,6)
    if name in ('3',"3'"):
        v=Pm[:,0]                      # project the basis state |h0> (a definite flux pair) onto this charge
        p=float(v@v); amps=np.unique(np.round(v/v[0],6))
        print("Q3 charge %-2s: probability %.4f | amplitude ratios to the h0 component: %s"%(name,p,amps.tolist()))
print('   multiplicities of irreps in the 12-dim rep:',mult)
print('   phi = %.6f, -1/phi = %.6f, 1/sqrt5 = %.6f'%(phi,-1/phi,1/5**.5))
