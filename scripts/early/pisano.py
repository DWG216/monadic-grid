import numpy as np, itertools
from math import isqrt
def pis(m):
    a,b,n=0,1,0
    while True:
        a,b=b,(a+b)%m; n+=1
        if (a,b)==(0,1): return n
def alpha(m):  # rank of apparition: first n>0 with F_n = 0 mod m
    a,b,n=0,1,0
    while True:
        a,b=b,(a+b)%m; n+=1
        if a==0: return n
primes=[p for p in range(2,2000) if all(p%q for q in range(2,isqrt(p)+1))]
print('pi/alpha takes values:',sorted({pis(p)//alpha(p) for p in primes}))
print("Wall's question pi(p^2) = p*pi(p) for all primes < 2000:",all(pis(p*p)==p*pis(p) for p in primes[:120]),'(checked first 120 primes)')
# modular group mod N: generated by S=[[0,-1],[1,0]], T=[[1,1],[0,1]]; projective (mod +-1)
def closure(gens,N):
    key=lambda M: min(tuple((M%N).flatten()),tuple((-M%N).flatten()))
    seen={key(np.eye(2,dtype=int)):np.eye(2,dtype=int)}; fr=[np.eye(2,dtype=int)]
    while fr:
        nw=[]
        for M in fr:
            for g in gens:
                P=(g@M)%N; k=key(P)
                if k not in seen: seen[k]=P; nw.append(P)
        fr=nw
    return seen
S=np.array([[0,-1],[1,0]]);T=np.array([[1,1],[0,1]]);Q2=np.array([[2,1],[1,1]])
for N,name in [(2,'dihedral S3'),(3,'tetrahedral A4'),(4,'octahedral S4'),(5,'icosahedral A5')]:
    G=closure([S,T],N)
    M=np.eye(2,dtype=int); k=0
    while True:
        M=(Q2@M)%N; k+=1
        if np.array_equal(M,np.eye(2,dtype=int)%N) or np.array_equal(M,(-np.eye(2,dtype=int))%N): break
    print('modular group mod %d: %d elements (%s) | Fibonacci step Q^2 has order %d there | Pisano period mod %d = %d'%(N,len(G),name,k,N,pis(N)))
