#!/usr/bin/env python3
"""Regenerate TEST_INDEX.md and MANIFEST.sha256 (maintainer tool)."""
import json, os, hashlib, re
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tests = json.load(open(os.path.join(HERE, 'tests.json')))
def first_line(path):
    try:
        for l in open(path, errors='ignore'):
            l = l.strip().lstrip('#').strip()
            if l: return l[:110]
    except FileNotFoundError: return ''
    return ''
rows = []
for t in tests:
    folder, name = t['script'].split('/')[-2], os.path.basename(t['script'])[:-3]
    key = f'{folder}__{name}' + ''.join('_' + str(x) for x in t.get('args', []))
    exp = os.path.exists(os.path.join(HERE, 'expected', key + '.out'))
    pre = ', '.join(t.get('predictions', [])) or '-'
    secs = ', '.join(t.get('sections', [])) or '-'
    args = ' '.join(t.get('args', []))
    rows.append(f"| `{t['script']}` {args} | {t['group']} | {secs} | {pre} | {'yes' if exp else 'no'} | {t.get('note', '')} |")
groups = {}
for t in tests: groups[t['group']] = groups.get(t['group'], 0) + 1
out = ['# Test index', '',
       'Generated by `tools/make_index.py` from `tests.json`. Columns: script (and arguments), run group, record sections that cite it, pre-registration files, whether a reference output is recorded in `expected/`, notes.', '',
       'Groups: ' + ', '.join(f'{k} {v}' for k, v in sorted(groups.items())) + '. `quick` and `early` run in seconds to a minute each; `heavy` can take up to hours; `broken` and `superseded` are kept for the record and not run by default.', '',
       '| Script | Group | Sections | Pre-registration | Reference output | Note |', '|---|---|---|---|---|---|'] + rows
open(os.path.join(HERE, 'TEST_INDEX.md'), 'w').write('\n'.join(out) + '\n')
man = []
for dp, dn, fs in os.walk(HERE):
    dn[:] = [d for d in dn if d not in ('results', '__pycache__')]
    for f in sorted(fs):
        p = os.path.join(dp, f); rel = os.path.relpath(p, HERE)
        if rel == 'MANIFEST.sha256': continue
        man.append(hashlib.sha256(open(p, 'rb').read()).hexdigest() + '  ' + rel)
open(os.path.join(HERE, 'MANIFEST.sha256'), 'w').write('\n'.join(sorted(man, key=lambda x: x.split('  ')[1])) + '\n')
print(len(rows), 'tests;', len(man), 'files in manifest')
